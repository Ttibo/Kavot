"""Planning's part of kavot.state.json: the default board and its one-time upgrades."""
from __future__ import annotations

from typing import Any

DEFAULT_COLUMNS = [
    {"id": 1, "name": "To do", "color": "#8c8c85", "position": 0, "is_done": False},
    {"id": 2, "name": "In progress", "color": "#d08b33", "position": 1, "is_done": False},
    {"id": 4, "name": "Review", "color": "#eab308", "position": 2, "is_done": False},
    {"id": 3, "name": "Done", "color": "#39917d", "position": 3, "is_done": True},
]


def initialize(state: dict[str, Any], timestamp: str) -> None:
    state["task_columns_version"] = 1
    state["task_columns"] = [{**item, "created_at": timestamp, "updated_at": timestamp} for item in DEFAULT_COLUMNS]


def migrate(state: dict[str, Any], timestamp: str) -> bool:
    from app.core.records.repository import JsonRepository
    changed = False
    # Upgrade the original board once; preserve customized workflows and
    # never recreate Review after a user deliberately removes it.
    if not state.get("task_columns_version"):
        columns = sorted(state["task_columns"], key=lambda item: (item["position"], item["id"]))
        if [item["name"] for item in columns] == ["To do", "In progress", "Done"]:
            done = columns[-1]
            review = next(item for item in DEFAULT_COLUMNS if item["name"] == "Review")
            state["task_columns"].append({
                **review, "id": JsonRepository.next_id(state, "task_columns"),
                "position": done["position"], "created_at": timestamp, "updated_at": timestamp,
            })
            done["position"] += 1
            done["updated_at"] = timestamp
        state["task_columns_version"] = 1
        changed = True
    # Retire only tasks generated by the former canvas tracking feature.
    # Archive and detach them once so their text stays recoverable, and a
    # deliberate restore makes them independent tasks.
    for task in state["tasks"]:
        if task.get("canvas_path") and task.get("canvas_node_id"):
            task["legacy_canvas_origin"] = {
                "path": task.pop("canvas_path"), "node_id": task.pop("canvas_node_id")
            }
            task["archived_at"] = task.get("archived_at") or timestamp
            task["updated_at"] = timestamp
            changed = True
    return changed
